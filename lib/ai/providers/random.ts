/** Small deterministic RNG so mock output varies by dream but is stable for the same input. */
export function hashString(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

export function rng(seed: number) {
  let a = seed || 1;
  const next = () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  return {
    next,
    int: (min: number, max: number) => Math.floor(next() * (max - min + 1)) + min,
    pick: <T,>(arr: readonly T[]): T => arr[Math.floor(next() * arr.length)],
    shuffle: <T,>(arr: readonly T[]): T[] => {
      const out = [...arr];
      for (let i = out.length - 1; i > 0; i--) {
        const j = Math.floor(next() * (i + 1));
        [out[i], out[j]] = [out[j], out[i]];
      }
      return out;
    },
  };
}

/** 1-2s pause so loading states can be seen. Override with MOCK_AI_DELAY_MS (e.g. 0 in scripts). */
export async function mockDelay(seed = Date.now()) {
  const fixed = process.env.MOCK_AI_DELAY_MS;
  const ms = fixed !== undefined && fixed !== "" ? Number(fixed) : 1000 + (seed % 1000);
  if (ms > 0) await new Promise((r) => setTimeout(r, ms));
}
